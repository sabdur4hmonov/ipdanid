export function mailText(locale: Locale, key: MailWord) {
  return scriptText({ en, uz, ru }[baseLocale(locale)][key], locale);
}
export function mailState(locale: Locale, state: string) {
  return mailText(
    locale,
    ([
      "in_app",
      "queued",
      "sending",
      "accepted",
      "checking",
      "delivered",
      "failed",
      "cancelled",
      "unknown",
    ].includes(state)
      ? state
      : "unknown") as MailWord,
  );
}
