export function spokenPin(locale: Locale, pin: number): string {
  if (locale !== "uz") return String(pin);
  const ones = [
      "nol",
      "bir",
      "ikki",
      "uch",
      "to‘rt",
      "besh",
      "olti",
      "yetti",
      "sakkiz",
      "to‘qqiz",
    ],
    tens = [
      "",
      "o‘n",
      "yigirma",
      "o‘ttiz",
      "qirq",
      "ellik",
      "oltmish",
      "yetmish",
      "sakson",
      "to‘qson",
    ];
  if (pin < 10) return ones[pin];
  if (pin < 100)
    return `${tens[Math.floor(pin / 10)]}${pin % 10 ? " " + ones[pin % 10] : ""}`;
  return `${ones[Math.floor(pin / 100)]} yuz${pin % 100 ? " " + spokenPin(locale, pin % 100) : ""}`;
}
